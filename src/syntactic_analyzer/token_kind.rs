#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TokenKind {
    IntLiteral,
    CharLiteral,
    Identifier,
    Operator,

    Array,
    Begin,
    Const,
    Do,
    Else,
    End,
    Func,
    If,
    In,
    Let,
    Of,
    Proc,
    Record,
    Then,
    Type,
    Var,
    While,

    Dot,
    Colon,
    Semicolon,
    Comma,
    Becomes,
    Is,

    LParen,
    RParen,
    LBracket,
    RBracket,
    LCurly,
    RCurly,

    Eof,
    Error,
}

impl TokenKind {
    pub fn keyword_of(spelling: &[u8]) -> Option<TokenKind> {
        match spelling {
            b"array" => Some(TokenKind::Array),
            b"begin" => Some(TokenKind::Begin),
            b"const" => Some(TokenKind::Const),
            b"do" => Some(TokenKind::Do),
            b"else" => Some(TokenKind::Else),
            b"end" => Some(TokenKind::End),
            b"func" => Some(TokenKind::Func),
            b"if" => Some(TokenKind::If),
            b"in" => Some(TokenKind::In),
            b"let" => Some(TokenKind::Let),
            b"of" => Some(TokenKind::Of),
            b"proc" => Some(TokenKind::Proc),
            b"record" => Some(TokenKind::Record),
            b"then" => Some(TokenKind::Then),
            b"type" => Some(TokenKind::Type),
            b"var" => Some(TokenKind::Var),
            b"while" => Some(TokenKind::While),
            _ => None,
        }
    }

    pub fn spelling(&self) -> &'static str {
        match self {
            TokenKind::Array => "array",
            TokenKind::Begin => "begin",
            TokenKind::Const => "const",
            TokenKind::Do => "do",
            TokenKind::Else => "else",
            TokenKind::End => "end",
            TokenKind::Func => "func",
            TokenKind::If => "if",
            TokenKind::In => "in",
            TokenKind::Let => "let",
            TokenKind::Of => "of",
            TokenKind::Proc => "proc",
            TokenKind::Record => "record",
            TokenKind::Then => "then",
            TokenKind::Type => "type",
            TokenKind::Var => "var",
            TokenKind::While => "while",
            TokenKind::Dot => ".",
            TokenKind::Colon => ":",
            TokenKind::Semicolon => ";",
            TokenKind::Comma => ",",
            TokenKind::Becomes => ":=",
            TokenKind::Is => "~",
            TokenKind::LParen => "(",
            TokenKind::RParen => ")",
            TokenKind::LBracket => "[",
            TokenKind::RBracket => "]",
            TokenKind::LCurly => "{",
            TokenKind::RCurly => "}",
            TokenKind::Eof => "",
            TokenKind::Error => "<error>",
            TokenKind::Identifier => "<identifier>",
            TokenKind::IntLiteral => "<int>",
            TokenKind::CharLiteral => "<char>",
            TokenKind::Operator => "<operator>",
        }
    }
}

