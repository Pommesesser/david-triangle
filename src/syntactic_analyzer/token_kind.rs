#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TokenKind {
    IntLiteral,
    CharLiteral,
    Identifier,
    Operator,

    Array,
    Begin,
    Const,
    Do,
    Else,
    End,
    Func,
    If,
    In,
    Let,
    Of,
    Proc,
    Record,
    Then,
    Type,
    Var,
    While,

    Dot,
    Colon,
    Semicolon,
    Comma,
    Becomes,
    Is,

    LParen,
    RParen,
    LBracket,
    RBracket,
    LCurly,
    RCurly,

    Eof,
    Error,
}

impl TokenKind {
    pub fn get_specific_token_for_identifier(spelling: &str) -> TokenKind {
        match spelling {
            "array" => TokenKind::Array,
            "begin" => TokenKind::Begin,
            "const" => TokenKind::Const,
            "do" => TokenKind::Do,
            "else" => TokenKind::Else,
            "end" => TokenKind::End,
            "func" => TokenKind::Func,
            "if" => TokenKind::If,
            "in" => TokenKind::In,
            "let" => TokenKind::Let,
            "of" => TokenKind::Of,
            "proc" => TokenKind::Proc,
            "record" => TokenKind::Record,
            "then" => TokenKind::Then,
            "type" => TokenKind::Type,
            "var" => TokenKind::Var,
            "while" => TokenKind::While,
            _ => TokenKind::Identifier,
        }
    }

    pub fn spelling(&self) -> &'static str {
        match self {
            TokenKind::Array => "array",
            TokenKind::Begin => "begin",
            TokenKind::Const => "const",
            TokenKind::Do => "do",
            TokenKind::Else => "else",
            TokenKind::End => "end",
            TokenKind::Func => "func",
            TokenKind::If => "if",
            TokenKind::In => "in",
            TokenKind::Let => "let",
            TokenKind::Of => "of",
            TokenKind::Proc => "proc",
            TokenKind::Record => "record",
            TokenKind::Then => "then",
            TokenKind::Type => "type",
            TokenKind::Var => "var",
            TokenKind::While => "while",
            TokenKind::Dot => ".",
            TokenKind::Colon => ":",
            TokenKind::Semicolon => ";",
            TokenKind::Comma => ",",
            TokenKind::Becomes => ":=",
            TokenKind::Is => "~",
            TokenKind::LParen => "(",
            TokenKind::RParen => ")",
            TokenKind::LBracket => "[",
            TokenKind::RBracket => "]",
            TokenKind::LCurly => "{",
            TokenKind::RCurly => "}",
            TokenKind::Eof => "",
            TokenKind::Error => "",
            TokenKind::Identifier => "<identifier>",
            TokenKind::IntLiteral => "<int>",
            TokenKind::CharLiteral => "<char>",
            TokenKind::Operator => "<operator>",
        }
    }
}